class TestExcelParser:
    def test_basic_excel(self, tmp_path):
        import openpyxl

        wb = openpyxl.Workbook()
        ws = wb.active
        ws.append(["Title", "Description", "Priority", "Category"])
        ws.append(["Login", "User login feature", "P0", "Auth"])
        ws.append(["Search", "Full-text search", "P1", "Core"])
        ws.append(["Export", "CSV export", "nice to have", "Data"])

        path = tmp_path / "reqs.xlsx"
        wb.save(str(path))

        reqs = parse_requirements_file(str(path))
        assert len(reqs) == 3
        assert reqs[0].title == "Login"
        assert reqs[0].priority == "P0"
        assert reqs[2].priority == "P2"  # "nice to have" → P2
        assert reqs[0].category == "Auth"

    def test_excel_alternate_headers(self, tmp_path):
        import openpyxl

        wb = openpyxl.Workbook()
        ws = wb.active
        ws.append(["Requirement Name", "Detail", "Importance"])
        ws.append(["SSO Login", "Single sign-on", "Critical"])
        ws.append(["Audit Trail", "Track actions", "Medium"])

        path = tmp_path / "reqs_alt.xlsx"
        wb.save(str(path))

        reqs = parse_requirements_file(str(path))
        assert len(reqs) == 2
        assert reqs[0].title == "SSO Login"
        assert reqs[0].priority == "P0"  # Critical → P0
